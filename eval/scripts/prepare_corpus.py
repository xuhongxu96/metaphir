#!/usr/bin/env python3
"""Prepare the MetaphIR evaluation corpus.

Everything is written into eval/corpus (gitignored), so it is regenerated by
rerunning this script rather than checked in:

1. Full opt benchmark: every `original/*.bc` module is preprocessed with the
   patched `opt` (the 20 selected folds are disabled), so the corpus is
   realistic O2 IR in which those folds never fired.

2. PR test cases: each PR's upstream InstCombine/InstSimplify regression test
   .ll file(s) are copied in directly, giving each fold guaranteed positives
   (and negatives) in the corpus.

A fresh clone rebuilds the corpus with
`eval/scripts/prepare_corpus.py --bench-root <llvm-opt-benchmark>/local`.
"""

from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from prs import PRS

REPO = Path(__file__).resolve().parents[2]
OPT = Path(
    os.environ.get("METAPHIR_OPT", REPO / "llvm-project" / "build" / "bin" / "opt")
)
# Local checkout of dtcxzyw/llvm-opt-benchmark (the directory holding one
# sub-directory per project, each with an `original/` folder of .bc files).
BENCH_ROOT_ENV = "METAPHIR_BENCH_ROOT"
LLVM_TEST_DIR = REPO / "llvm-project" / "llvm" / "test" / "Transforms"
PASSES = "default<O2>"

PR_TEST_PREFIX = "pr"


def collect_pr_tests(corpus: Path) -> int:
    """Copy each PR's upstream test file(s) into the corpus.

    A test file shared by several PRs is copied once, named after the first PR
    that lists it, so its functions are not counted twice.
    """
    count = 0
    copied: dict[str, str] = {}
    for pr, entry in PRS.items():
        for rel in entry.tests:
            if rel in copied:
                print(f"  {pr}: {Path(rel).name} (shared with {copied[rel]})")
                continue
            source = LLVM_TEST_DIR / rel
            if not source.is_file():
                print(f"  WARN {pr}: missing test {rel}", file=sys.stderr)
                continue
            dst = corpus / f"{pr}__{Path(rel).name}"
            shutil.copy(source, dst)
            copied[rel] = pr
            count += 1
            print(f"  {pr}: {Path(rel).name} -> {dst.name}")
    return count


def is_pr_test(path: Path) -> bool:
    return path.suffix == ".ll" and path.name.startswith(PR_TEST_PREFIX)


def pipeline_without(pipeline: str, pass_name: str) -> str:
    """A textual pass pipeline with every occurrence of ``pass_name`` removed.

    Pass managers left empty, e.g. "function<eager-inv>()", are dropped too.
    """
    name = rf"(?<![\w-]){re.escape(pass_name)}(?:<[^<>()]*>)?(?![\w<(-])"
    if not re.search(name, pipeline):
        sys.exit(f"{pass_name} is not in the pipeline")
    out = re.sub(name, "", pipeline)
    while True:
        tidy = re.sub(r",(?=[,)])|(?<=\(),|^,|,$", "", out)
        tidy = re.sub(r"[\w-]+(?:<[^<>()]*>)?\(\)", "", tidy)
        if tidy == out:
            return out
        out = tidy


def default_pipeline(opt: Path, passes: str) -> str:
    """The textual pipeline that ``opt -passes=<passes>`` runs."""
    proc = subprocess.run(
        [str(opt), f"-passes={passes}", "-print-pipeline-passes", "-disable-output"],
        input="",
        capture_output=True,
        text=True,
        check=True,
    )
    return proc.stdout.strip()


def preprocess_benchmark(
    bench_root: Path, corpus: Path, passes: str, jobs: int, opt: Path
) -> tuple[int, int]:
    """Preprocess every `original/*.bc` module into the corpus directory."""
    entries: list[tuple[str, Path]] = []
    for proj_dir in sorted(bench_root.iterdir()):
        if not proj_dir.is_dir():
            continue
        original = proj_dir / "original"
        if not original.is_dir():
            continue
        proj = proj_dir.name
        for bc in sorted(original.glob("*.bc")):
            entries.append((f"{proj}__{bc.stem}.bc", bc))
    print(f"== preprocess {len(entries)} modules from {bench_root} ==")

    def one(item: tuple[int, tuple[str, Path]], tmp: Path) -> tuple[bool, str]:
        index, (name, src) = item
        tmp_bc = tmp / f"{index}.bc"
        env = dict(os.environ)
        env.pop("METAPHIR_EVAL_ENABLED", None)  # ensure folds stay disabled
        proc = subprocess.run(
            [str(opt), f"-passes={passes}", str(src), "-o", str(tmp_bc)],
            capture_output=True,
            text=True,
            check=False,
            env=env,
        )
        if proc.returncode != 0:
            first = next(iter(proc.stderr.splitlines()), "")
            return False, f"  PREPROCESS FAILED {src}: {first}"
        shutil.move(str(tmp_bc), corpus / name)
        return True, ""

    ok = fail = 0
    with tempfile.TemporaryDirectory(prefix="metaphir-prep-") as tmp:
        tmp_path = Path(tmp)
        with ThreadPoolExecutor(max_workers=jobs) as pool:
            results = pool.map(lambda item: one(item, tmp_path), enumerate(entries))
            for success, message in results:
                if success:
                    ok += 1
                else:
                    print(message, file=sys.stderr)
                    fail += 1
    return ok, fail


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--bench-root",
        type=Path,
        default=os.environ.get(BENCH_ROOT_ENV),
        help=f"llvm-opt-benchmark root (default: ${BENCH_ROOT_ENV})",
    )
    ap.add_argument("--opt", type=Path, default=OPT)
    ap.add_argument("--passes", default=PASSES)
    ap.add_argument("--corpus", type=Path, default=REPO / "eval" / "corpus")
    ap.add_argument("--jobs", type=int, default=os.cpu_count() or 1)
    ap.add_argument(
        "--drop-pass",
        action="append",
        default=[],
        metavar="PASS",
        help="remove every occurrence of PASS from --passes (repeatable), "
        "e.g. --drop-pass instcombine",
    )
    ap.add_argument(
        "--skip-benchmark",
        action="store_true",
        help="only copy the PR test cases into the corpus",
    )
    args = ap.parse_args()

    if args.jobs < 1:
        ap.error("--jobs must be at least 1")
    if not args.opt.is_file():
        sys.exit(f"opt not found: {args.opt} (is the Release LLVM built?)")

    if not args.skip_benchmark:
        if args.bench_root is None:
            ap.error(f"--bench-root or ${BENCH_ROOT_ENV} is required")
        if not args.bench_root.is_dir():
            sys.exit(f"benchmark root not found: {args.bench_root}")

    # Fresh corpus: drop previous contents. With --skip-benchmark only the PR
    # test copies are replaced; the preprocessed modules are kept.
    if args.corpus.is_dir():
        for old in args.corpus.iterdir():
            if old.is_file() and (not args.skip_benchmark or is_pr_test(old)):
                old.unlink()
    args.corpus.mkdir(parents=True, exist_ok=True)

    count = collect_pr_tests(args.corpus)
    print(f"  collected {count} PR test file(s)")

    if args.skip_benchmark:
        return 0

    passes = args.passes
    if args.drop_pass:
        passes = default_pipeline(args.opt, passes)
        for name in args.drop_pass:
            passes = pipeline_without(passes, name)
        print(f"  passes: {passes}")
    ok, fail = preprocess_benchmark(
        args.bench_root, args.corpus, passes, args.jobs, args.opt
    )
    print(f"  preprocessed {ok} benchmark modules, {fail} failed")
    print(f"  corpus: {args.corpus}")
    return 0 if fail == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
